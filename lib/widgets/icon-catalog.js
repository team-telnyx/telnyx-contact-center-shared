export const WIDGET_ICON_IDS = Object.freeze(WIDGET_ICON_CATALOG.map(([id]) => id));

export function normalizeWidgetIconId(value, fallback = "message-circle") {
  const aliases = {
    message: "message-circle",
    chat: "messages-square",
  };
  const candidate = aliases[value] || value;
  return WIDGET_ICON_IDS.includes(candidate) ? candidate : fallback;
}
